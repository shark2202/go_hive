// flatSurfaceGroupedModule reports whether a live definition is a grouped
// integration module (one tool per module with an `action` enum) rather than
// a flat one-action tool. The lazy layer carries flat names only, matching
// the Python one-tool-per-action shape; grouped modules keep their grouped
// surface and stay out of the deferred manifest.
func flatSurfaceGroupedModule(def llm.ToolDef) bool {
	properties, ok := def.Parameters["properties"].(map[string]any)
	if !ok {
		return false
	}
	_, grouped := properties["action"]
	return grouped
}

// EagerModelDefNames returns the always-on flat names this catalogue actually
// advertises, in the captured upstream order. The server's chat tool tier
// uses it as the first-request surface.
func (c *sessionToolCatalogue) EagerModelDefNames() []string {
	if c == nil || !flatToolSurfaceEnabled() {
		return nil
	}
	live := map[string]struct{}{}
	for _, def := range c.flatModelDefs() {
		live[def.Name] = struct{}{}
	}
	out := make([]string, 0, len(flatSurfaceEagerOrder))
	for _, name := range flatSurfaceEagerOrder {
		if _, ok := live[name]; ok {
			out = append(out, name)
		}
	}
	return out
}

// LazyModelDefs returns the definitions the lazy layer can load on demand
// (Python's searchable tier): the default-surface names not in the eager
// order — the lifecycle/colony layer — followed by the flat directory tools
// outside the default surface that this build can execute. Grouped
// integration modules are excluded; they remain registered and reachable by
// name and through HIVE_TOOL_SURFACE=grouped.
func (c *sessionToolCatalogue) LazyModelDefs() []llm.ToolDef {
	if c == nil || !flatToolSurfaceEnabled() {
		return nil
	}
	eager := flatSurfaceEagerNameSet()
	defaultNames := map[string]struct{}{}
	for _, name := range flatSurfaceDefaultNames() {
		defaultNames[name] = struct{}{}
	}
	out := make([]llm.ToolDef, 0, len(c.defs))
	seen := map[string]struct{}{}
	// Deferred default-surface leftovers keep their flat projection (same
	// schema policy as ModelDefs).
	for _, def := range c.flatModelDefs() {
		if _, isEager := eager[def.Name]; isEager {
			continue
		}
		seen[def.Name] = struct{}{}
		out = append(out, def)
	}
	// Flat directory tools: live catalogue definitions outside the default
	// surface with a flat name shape (no `action` module switch).
	for _, def := range c.defs {
		if def.Name == "" {
			continue
		}
		if _, isDefault := defaultNames[def.Name]; isDefault {
			continue
		}
		if _, dup := seen[def.Name]; dup {
			continue
		}
		if flatSurfaceGroupedModule(def) {
			continue
		}
		seen[def.Name] = struct{}{}
		out = append(out, def)
	}
	return out
}

// LazySurfaceDeps is the loader-facing view of the flat lazy layer: the
// ordered always-on names and the deferred definitions, or nils when the
// grouped surface is selected (grouped mode keeps the pre-change surface).
func (c *sessionToolCatalogue) LazySurfaceDeps() (eager []string, deferred []llm.ToolDef) {
	if c == nil || !flatToolSurfaceEnabled() {
		return nil, nil
	}
	return c.EagerModelDefNames(), c.LazyModelDefs()
}

// flatSurfaceToolDef converts one frozen entry into the advertised definition.
func flatSurfaceToolDef(entry flatSurfaceTool) llm.ToolDef {
	parameters := entry.InputSchema
	if parameters == nil {
		parameters = map[string]any{"type": "object", "properties": map[string]any{}}
	}
	return llm.ToolDef{
		Name:        entry.Name,
		Description: entry.Description,
		Parameters:  parameters,
	}
}

// ModelDefs returns the tool definitions a chat session advertises to the
// model. Flat mode (the default) advertises the Python reference default set;
// grouped mode returns the complete catalogue exactly as before.
func (c *sessionToolCatalogue) ModelDefs() []llm.ToolDef {
	if c == nil {
		return nil
	}
	if !flatToolSurfaceEnabled() {
		return c.defs
	}
	return c.flatModelDefs()
}

// flatModelDefs projects the catalogue onto the 39 default-set names. Names
// with a live definition keep it only for the documented exceptions; everything
// else takes the frozen Python description/schema. A lifecycle name with no
// live definition means the catalogue is not a queen session (the binding was
// never enabled), so it is not advertised.
func (c *sessionToolCatalogue) flatModelDefs() []llm.ToolDef {
	manifest := flatSurfaceManifest()
	keep := flatSurfaceKeepCurrentNames()
	live := make(map[string]llm.ToolDef, len(c.defs))
	for _, def := range c.defs {
		if def.Name == "" {
			continue
		}
		if _, duplicate := live[def.Name]; duplicate {
			continue
		}
		live[def.Name] = def
	}
	out := make([]llm.ToolDef, 0, len(manifest.Tools))
	for _, entry := range manifest.Tools {
		if def, ok := live[entry.Name]; ok {
			if _, keepLive := keep[entry.Name]; keepLive {
				out = append(out, def)
				continue
			}
			out = append(out, flatSurfaceToolDef(entry))
			continue
		}
		if _, standalone := flatSurfaceStandaloneTools[entry.Name]; standalone {
			out = append(out, flatSurfaceToolDef(entry))
		}
	}
	return out
}

// flatSurfacePlaybookActions maps the flat playbook-control names onto the
// actions the existing run_playbook implementation already serves. Python
// exposes these as separate tools; Go carries them as run_playbook actions, so
// the flat name is a routing alias, not a second implementation.
var flatSurfacePlaybookActions = map[string]string{
	"get_playbook_status": "status",
	"list_playbook_runs":  "status",
	"stop_playbook":       "stop",
}

// executeFlatSurfaceTool routes a flat default-set call this build does not
// already handle by name. It runs only in flat mode: grouped mode keeps the
// pre-change routing (the names were never registered there).
func (c *sessionToolCatalogue) executeFlatSurfaceTool(ctx context.Context, name string, input map[string]any) (string, bool, bool) {
	if !flatToolSurfaceEnabled() {
		return "", false, false
	}
	if action, ok := flatSurfacePlaybookActions[name]; ok {
		mapped := make(map[string]any, len(input)+1)
		for key, value := range input {
			if key == "action" {
				continue
			}
			mapped[key] = value
		}
		mapped["action"] = action
		content, isError := colony.RunPlaybook(ctx, colony.RunWorkerSpawnerFromContext(ctx), mapped)
		return content, isError, true
	}
	switch name {
	case "search_tools":
		// The agent loop answers search_tools itself when the session has a
		// tool tier. Reaching the catalogue means there is no deferred surface
		// at all: answer with the inventory shape instead of an unknown tool.
		return tools.PythonJSONDumps(map[string]any{
			"status":      "ok",
			"loaded":      flatSurfaceDefaultNames(),
			"searchable":  []string{},
			"disabled":    []string{},
			"unavailable": []string{},
			"note": "This session advertises the Python reference default tool set as flat names; " +
				"no tools are deferred. Grouped integration tools are hidden by default and can be " +
				"enabled with HIVE_TOOL_SURFACE=grouped.",
		}), false, true
	case "collect_result", "credentials", "sentinel_setup", "suggest_colony":
		return tools.PythonJSONDumps(map[string]any{
			"error":   "not_implemented",
			"tool":    name,
			"message": flatSurfaceNotImplementedMessage(name),
		}), true, true
	}
	return "", false, false
}

// flatSurfaceNotImplementedMessage explains, per name, why the tool is
// advertised without an executor and what to use instead. Advertised-not-
// working beats the silent alternative (the name would otherwise be missing
// from the Python-parity surface).
func flatSurfaceNotImplementedMessage(name string) string {
	switch name {
	case "collect_result":
		return "collect_result is part of the Python default surface, but this build does not run " +
			"background tool handles. Long-running terminal work is collected with " +
			"terminal_job_logs(job_id, wait_until_exit=true), or terminal_job_manage to stop it."
	case "credentials":
		return "credentials is not ported as a model tool in this build. Use the `hive-cred` CLI from " +
			"terminal_exec instead: `hive-cred browse --json`, `hive-cred inspect <id> --json`, " +
			"`hive-cred token <id> --account <alias>`."
	case "sentinel_setup":
		return "sentinel_setup is not ported as a model tool in this build. Sentinel notifications are " +
			"configured through the desktop/UI connector for the colony."
	case "suggest_colony":
		return "suggest_colony is not ported as a model tool in this build. Create the colony from the " +
			"UI; this chat keeps working in place."
	default:
		return name + " is part of the Python default surface but has no implementation in this build."
	}
}
