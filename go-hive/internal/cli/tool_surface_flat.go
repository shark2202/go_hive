const (
	// ToolSurfaceEnvVar selects the model-visible chat tool surface.
	//   unset / "flat"  Python reference default set, flat names (default)
	//   "grouped"       the historical catalogue: grouped integration modules
	//                   (`airtable` + action) plus every other registered tool
	ToolSurfaceEnvVar = "HIVE_TOOL_SURFACE"
	// ToolSurfaceFlat is the default: one flat tool name per action.
	ToolSurfaceFlat = "flat"
	// ToolSurfaceGrouped restores the grouped-module surface.
	ToolSurfaceGrouped = "grouped"
)

//go:embed tool_surface_flat.json
var toolSurfaceFlatJSON []byte

// flatSurfaceTool is one default-set tool of the frozen Python reference.
type flatSurfaceTool struct {
	Name        string         `json:"name"`
	Description string         `json:"description"`
	InputSchema map[string]any `json:"input_schema"`
	Layers      []string       `json:"layers"`
}

type flatSurfaceManifestDoc struct {
	SchemaVersion string              `json:"schema_version"`
	Kind          string              `json:"kind"`
	Provenance    map[string]any      `json:"provenance"`
	LayerCounts   map[string]int      `json:"layer_counts"`
	Layers        map[string][]string `json:"layers"`
	Tools         []flatSurfaceTool   `json:"tools"`
}

var flatSurfaceOnce = sync.OnceValues(func() (*flatSurfaceManifestDoc, error) {
	var doc flatSurfaceManifestDoc
	if err := json.Unmarshal(toolSurfaceFlatJSON, &doc); err != nil {
		return nil, fmt.Errorf("flat tool surface manifest: %w", err)
	}
	if len(doc.Tools) == 0 {
		return nil, fmt.Errorf("flat tool surface manifest: no tools")
	}
	return &doc, nil
})

// flatSurfaceManifest returns the embedded Python default surface. A malformed
// manifest is a check-in bug (the file is embedded and covered by tests), so it
// fails loudly instead of silently falling back to the grouped surface.
func flatSurfaceManifest() *flatSurfaceManifestDoc {
	doc, err := flatSurfaceOnce()
	if err != nil {
		panic(err)
	}
	return doc
}

// toolSurfaceMode resolves the requested surface. Only an explicit "grouped"
// (or "full") selects the legacy surface: an unset or unrecognised value keeps
// the flat default so grouping cannot leak into a default request by typo.
func toolSurfaceMode() string {
	switch strings.ToLower(strings.TrimSpace(os.Getenv(ToolSurfaceEnvVar))) {
	case ToolSurfaceGrouped, "full":
		return ToolSurfaceGrouped
	default:
		return ToolSurfaceFlat
	}
}

// flatToolSurfaceEnabled reports whether the default flat surface is active.
func flatToolSurfaceEnabled() bool { return toolSurfaceMode() == ToolSurfaceFlat }

// flatSurfaceDefaultNames returns the frozen default set in canonical order.
func flatSurfaceDefaultNames() []string {
	manifest := flatSurfaceManifest()
	names := make([]string, 0, len(manifest.Tools))
	for _, entry := range manifest.Tools {
		names = append(names, entry.Name)
	}
	return names
}

