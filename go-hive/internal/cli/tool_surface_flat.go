// flatSurfaceLifecycleOnly reports whether the frozen entry comes from the
// lifecycle layer alone. Python's Tool Library renders those rows with a name
// and description but no input schema, so the Go schema is strictly richer and
// is kept (docs/tool-contract-diff.md §11.4 records the layer gap).
func flatSurfaceLifecycleOnly(entry flatSurfaceTool) bool {
	lifecycle := false
	for _, layer := range entry.Layers {
		switch layer {
		case "llm_request", "synthetic":
			return false
		case "lifecycle":
			lifecycle = true
		}
	}
	return lifecycle
}

// flatSurfaceKeepCurrentNames is the documented exception list of the flat
// projection: names that keep the live Go definition instead of the frozen
// Python one.
//
//   - every tool in the P1 parity manifest (tool_contract_parity.json): those
//     schemas were already frozen against Python by the P1/terminal lanes and
//     must not be rewritten here;
//   - lifecycle-only entries (with a live definition at call time): the
//     Python Tool Library row has no schema, so the Go schema is the only
//     executable contract.
func flatSurfaceKeepCurrentNames() map[string]struct{} {
	out := map[string]struct{}{}
	for name := range toolContractParityManifestData().Tools {
		out[name] = struct{}{}
	}
	for _, entry := range flatSurfaceManifest().Tools {
		if flatSurfaceLifecycleOnly(entry) {
			out[entry.Name] = struct{}{}
		}
	}
	return out
}

