package cli

// Default flat tool surface for chat sessions.
//
// The Python reference (hive 1.0.14) advertises 24 flat tools in a default
// queen session's first LLM request; every tool has its own name and no
// grouped `action` switcher. The Go catalogue historically advertised 144
// names, 87 of them grouped integration modules (`airtable`, `slack`, ...),
// so the model-visible names could never line up with Python.
//
// This file makes the model-visible default a projection of the frozen Python
// contract instead of the internal pool:
//
//   - the default set is the reference layers llm_request ∪ lifecycle ∪
//     synthetic from contracts/tool-definitions.json: 24 + 16 + 1 entries,
//     39 unique names (ask_user is in llm_request+synthetic, write_skill in
//     llm_request+lifecycle). mcp_catalog is the Tool Library / deferred
//     layer, not part of the default request.
//   - name/description/input_schema come from the frozen contract
//     (tool_surface_flat.json, generated by
//     go_hive/scripts/gen_tool_surface_flat.py). Two documented exceptions
//     keep the live Go definition: the P1-frozen tools
//     (tool_contract_parity.json) and lifecycle entries whose Python Tool
//     Library row carries no input schema (layer gap, §11.4 of
//     docs/tool-contract-diff.md).
//   - the grouped integration modules stay registered: they are still in
//     sessionToolCatalogue.defs, the Tool Library catalog, the `@server:`
//     categories and the colony worker declared-tool pool. They are simply
//     not advertised in the default model request. Calling a grouped name
//     explicitly keeps its existing execution route.
//   - HIVE_TOOL_SURFACE=grouped restores the pre-flat surface (the full
//     catalogue) for a session; unset, `flat`, or any unknown value keeps the
//     default flat surface, so grouping is never exposed by accident.
//
// Execution routing is unchanged: a flat name runs through the same builtin,
// task, skills, colony or registry executor it always did. The only new
// routes are the three playbook-control names Python exposes separately but
// Go carries as run_playbook actions (see executeFlatSurfaceTool). Names the
// port has no implementation for still get advertised (name parity) and
// answer with an explicit not_implemented envelope instead of an unknown-tool
// error.
//
// Lazy layer (Python Tool Library parity): the first request advertises only
// the 24 always-on names of the reference's `llm_request` layer, in the
// captured upstream order (flatSurfaceEagerOrder). Everything else the build
// can execute is deferred: the 15 remaining default-surface names (the
// lifecycle/colony layer) plus the flat "directory" tools outside the default
// surface (chart_render, web_scrape, web_search, file ops, tracker_*,
// skill_view/list_skills, credential_status, terminal advanced, csv/excel
// aliases, ...). Deferred tools are announced by name in the searchable-tools
// reminder and loaded on demand with search_tools, exactly like Python's
// eager/searchable split. Grouped integration modules stay out of the lazy
// layer (they are module+action tools, not flat names) and keep their grouped
// surface and explicit-call routes.
//
// Numbers after this change: catalogue pool 137 (+10 queen lifecycle) =
// internal registry; default flat surface 39; first request 24 (Python
// reference parity); deferred flat layer = 15 lifecycle/colony + flat
// directory tools; grouped switch back to the full pool.
//
// Parity: framework/tools/tool_tiers.py (eager vs searchable split)
// Parity: framework/agents/queen/queen_tools_defaults.py::always_enabled_tool_names
// Parity: framework/agent_loop/agent_loop.py (tools[] assembled per turn)

