// SurfaceMode resolves the requested surface. Only an explicit "grouped" (or
// "full") selects the legacy surface: an unset or unrecognised value keeps the
// flat default so grouping cannot leak into a default request by typo.
func SurfaceMode() string {
	switch strings.ToLower(strings.TrimSpace(os.Getenv(SurfaceEnvVar))) {
	case SurfaceGrouped, "full":
		return SurfaceGrouped
	default:
		return SurfaceFlat
	}
}

// FlatEnabled reports whether the default flat surface is active.
func FlatEnabled() bool { return SurfaceMode() == SurfaceFlat }

// LifecycleOnly reports whether the frozen entry comes from the lifecycle
// layer alone. Python's Tool Library renders those rows with a name and
// description but no input schema, so the Go schema is strictly richer and is
// kept (docs/tool-contract-diff.md §11.4 records the layer gap).
func LifecycleOnly(entry FlatTool) bool {
	lifecycle := false
	for _, layer := range entry.Layers {
		switch layer {
		case "llm_request", "synthetic":
			return false
		case "lifecycle":
			lifecycle = true
		}
	}
	return lifecycle
}

// ToolDef converts one frozen entry into the advertised definition.
func ToolDef(entry FlatTool) llm.ToolDef {
	parameters := entry.InputSchema
	if parameters == nil {
		parameters = map[string]any{"type": "object", "properties": map[string]any{}}
	}
	return llm.ToolDef{
		Name:        entry.Name,
		Description: entry.Description,
		Parameters:  parameters,
	}
}

// KeepCurrentNames is the documented exception list of the flat projection:
// names that keep the live Go definition instead of the frozen Python one.
//
//   - every tool in the P1 parity manifest (tool_contract_parity.json): those
//     schemas were already frozen against Python by the P1/terminal lanes and
//     must not be rewritten here;
//   - lifecycle-only entries (with a live definition at call time): the Python
//     Tool Library row has no schema, so the Go schema is the only executable
//     contract.
func (m *Manifest) KeepCurrentNames(parity map[string]struct{}) map[string]struct{} {
	out := map[string]struct{}{}
	for name := range parity {
		out[name] = struct{}{}
	}
	for _, entry := range m.Tools {
		if LifecycleOnly(entry) {
			out[entry.Name] = struct{}{}
		}
	}
	return out
}

// ModelDefs projects the catalogue defs onto the 39 default-set names. Names
// with a live definition keep it only for the documented exceptions; everything
// else takes the frozen Python description/schema. A lifecycle name with no
// live definition means the catalogue is not a queen session (the binding was
// never enabled), so it is not advertised.
func (m *Manifest) ModelDefs(defs []llm.ToolDef, keep map[string]struct{}) []llm.ToolDef {
	live := make(map[string]llm.ToolDef, len(defs))
	for _, def := range defs {
		if def.Name == "" {
			continue
		}
		if _, duplicate := live[def.Name]; duplicate {
			continue
		}
		live[def.Name] = def
	}
	out := make([]llm.ToolDef, 0, len(m.Tools)+len(ColonyPhaseOnly))
	for _, entry := range m.Tools {
		if def, ok := live[entry.Name]; ok {
			if _, keepLive := keep[entry.Name]; keepLive {
				out = append(out, def)
				continue
			}
			out = append(out, ToolDef(entry))
			continue
		}
		if _, standalone := StandaloneTools[entry.Name]; standalone {
			out = append(out, ToolDef(entry))
		}
	}
	// Colony-phase-only extensions: not in the frozen default set, advertised
	// only while a colony is bound (the server gate drops them otherwise).
	for _, name := range m.SortedColonyPhaseOnlyNames() {
		if def, ok := live[name]; ok {
			out = append(out, def)
		}
	}
	return out
}

// LazyModelDefs returns the definitions the lazy layer can load on demand
// (Python's searchable tier): the default-surface names not in the eager
// order — the lifecycle/colony layer — followed by the flat directory tools
// outside the default surface that this build can execute. Grouped
// integration modules are excluded; they remain registered and reachable by
// name and through HIVE_TOOL_SURFACE=grouped.
func (m *Manifest) LazyModelDefs(defs []llm.ToolDef, keep map[string]struct{}) []llm.ToolDef {
	eager := EagerNameSet()
	defaultNames := map[string]struct{}{}
	for _, name := range m.DefaultNames() {
		defaultNames[name] = struct{}{}
	}
	out := make([]llm.ToolDef, 0, len(defs))
	seen := map[string]struct{}{}
	// Deferred default-surface leftovers keep their flat projection (same
	// schema policy as ModelDefs).
	for _, def := range m.ModelDefs(defs, keep) {
		if _, isEager := eager[def.Name]; isEager {
			continue
		}
		seen[def.Name] = struct{}{}
		out = append(out, def)
	}
	// Flat directory tools: live catalogue definitions outside the default
	// surface with a flat name shape (no `action` module switch, or an
	// operation-enum tool exempted like the browser and lsp adapters).
	for _, def := range defs {
		if def.Name == "" {
			continue
		}
		if _, isDefault := defaultNames[def.Name]; isDefault {
			continue
		}
		if _, dup := seen[def.Name]; dup {
			continue
		}
		if GroupedModule(def) {
			continue
		}
		seen[def.Name] = struct{}{}
		out = append(out, def)
	}
	return out
}

// EagerModelDefNames returns the always-on flat names this catalogue actually
// advertises, in the captured upstream order. The server's chat tool tier uses
// it as the first-request surface.
func (m *Manifest) EagerModelDefNames(defs []llm.ToolDef, keep map[string]struct{}) []string {
	live := map[string]struct{}{}
	for _, def := range m.ModelDefs(defs, keep) {
		live[def.Name] = struct{}{}
	}
	out := make([]string, 0, len(EagerOrder))
	for _, name := range EagerOrder {
		if _, ok := live[name]; ok {
			out = append(out, name)
		}
	}
	return out
}

// EagerNameSet is the eager membership set (24 names).
func EagerNameSet() map[string]struct{} {
	out := make(map[string]struct{}, len(EagerOrder))
	for _, name := range EagerOrder {
		out[name] = struct{}{}
	}
	return out
}

// SortedColonyPhaseOnlyNames returns the colony-phase-only names in stable
// (bytewise) order so the advertised tail is deterministic.
func (m *Manifest) SortedColonyPhaseOnlyNames() []string {
	names := make([]string, 0, len(ColonyPhaseOnly))
	for name := range ColonyPhaseOnly {
		names = append(names, name)
	}
	sort.Strings(names)
	return names
}

// GroupedModule reports whether a live definition is a grouped integration
// module (one tool per module with an `action` enum) rather than a flat
// one-action tool. The lazy layer carries flat names only, matching the Python
// one-tool-per-action shape; grouped modules keep their grouped surface and
// stay out of the deferred manifest.
//
// The browser tools are flat by construction even though browser_interact and
// browser_dialog_respond legitimately take an `action` argument — the gcu
// surface registers one tool per operation, so they are exempt from the module
// heuristic. The same holds for the read-only lsp tool: its `action` enum
// selects a read-only operation, not a grouped integration module.
func GroupedModule(def llm.ToolDef) bool {
	if _, flat := actionNamedFlatNames()[def.Name]; flat {
		return false
	}
	properties, ok := def.Parameters["properties"].(map[string]any)
	if !ok {
		return false
	}
	_, grouped := properties["action"]
	return grouped
}

var actionNamedFlatOnce = sync.OnceValue(func() map[string]struct{} {
	names := map[string]struct{}{}
	for _, name := range integrations.BrowserToolNames() {
		names[name] = struct{}{}
	}
	// lsp is a flat, read-only code-intelligence tool with an operation enum;
	// keep it in the lazy layer like the browser operations.
	names[builtin.ToolLSP] = struct{}{}
	return names
})

func actionNamedFlatNames() map[string]struct{} {
	return actionNamedFlatOnce()
}

// NotImplementedMessage explains, per name, why the tool is advertised without
// an executor and what to use instead. Advertised-not-working beats the silent
// alternative (the name would otherwise be missing from the Python-parity
// surface).
func NotImplementedMessage(name string) string {
	switch name {
	case "collect_result":
		return "collect_result is executed by the agent loop's background-tool registry, not by " +
			"the tool catalogue. A background-capable tool (image_generate, terminal_exec) started " +
			"in a session turn returns a bg_* handle; pass that handle to collect_result in the " +
			"same session — it waits for the work and returns the real result, or " +
			"{\"status\":\"pending\"} if a new message arrives first."
	case "suggest_colony":
		return "suggest_colony is not ported as a model tool in this build. Create the colony from the " +
			"UI; this chat keeps working in place."
	default:
		return name + " is part of the Python default surface but has no implementation in this build."
	}
}
