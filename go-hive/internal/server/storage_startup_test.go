// storageFixtureGenerator resolves go_hive/scripts/storage_compat_gen_fixture.py
// from the package directory (go test runs with cwd = package dir). It is the
// same generator the storage-compat double run uses, so the fixtures here are
// byte-identical to the recorded reference.
func storageFixtureGenerator(t *testing.T) string {
	t.Helper()
	script := filepath.Clean(filepath.Join("..", "..", "..", "scripts", "storage_compat_gen_fixture.py"))
	if _, err := os.Stat(script); err != nil {
		t.Skipf("storage fixture generator not present (standalone checkout): %v", err)
	}
	if _, err := exec.LookPath("python3"); err != nil {
		t.Skip("python3 not on PATH; fixtures are generated by the stdlib-only storage compat script")
	}
	return script
}

func buildStorageFixture(t *testing.T, version string) string {
	t.Helper()
	script := storageFixtureGenerator(t)
	home := filepath.Join(t.TempDir(), "home")
	if out, err := exec.Command("python3", script, "--dest", home, "--version", version).CombinedOutput(); err != nil {
		t.Fatalf("generate %s fixture: %v\n%s", version, err, out)
	}
	if out, err := exec.Command("python3", script, "--fix-paths", home).CombinedOutput(); err != nil {
		t.Fatalf("fix %s fixture paths: %v\n%s", version, err, out)
	}
	return home
}

type storageHomeTree struct {
	files map[string]string // slash-separated relative path -> sha256 hex
	dirs  []string          // slash-separated relative dirs, sorted
}

func walkStorageHome(t *testing.T, root string) storageHomeTree {
	t.Helper()
	tree := storageHomeTree{files: map[string]string{}}
	err := filepath.WalkDir(root, func(path string, entry os.DirEntry, walkErr error) error {
		if walkErr != nil {
			return walkErr
		}
		rel, relErr := filepath.Rel(root, path)
		if relErr != nil {
			return relErr
		}
		if rel == "." {
			return nil
		}
		rel = filepath.ToSlash(rel)
		if entry.IsDir() {
			tree.dirs = append(tree.dirs, rel)
			return nil
		}
		raw, readErr := os.ReadFile(path)
		if readErr != nil {
			return readErr
		}
		sum := sha256.Sum256(raw)
		tree.files[rel] = hex.EncodeToString(sum[:])
		return nil
	})
	if err != nil {
		t.Fatalf("walk %s: %v", root, err)
	}
	sort.Strings(tree.dirs)
	return tree
}

func (tree storageHomeTree) fileNames() []string {
	names := make([]string, 0, len(tree.files))
	for name := range tree.files {
		names = append(names, name)
	}
	sort.Strings(names)
	return names
}

// storageTreeGolden mirrors the subset of docs/storage-compat/*-tree-diff.json
// needed to reconstruct the reference post-migration inventory: files that
// compared equal plus the opaque SQLite files (byte diffs are expected there),
// and every directory both implementations produced.
type storageTreeGolden struct {
	Equal         []string `json:"equal"`
	ChangedOpaque []string `json:"changed_opaque"`
	OnlyPy        []string `json:"only_py"`
	OnlyGo        []string `json:"only_go"`
	DirsOnlyPy    []string `json:"dirs_only_py"`
	DirsOnlyGo    []string `json:"dirs_only_go"`
	PyDirs        []string `json:"py_dirs"`
}

func loadStorageTreeGolden(t *testing.T, label string) storageTreeGolden {
	t.Helper()
	path := filepath.Join("..", "..", "..", "..", "docs", "storage-compat", label+"-tree-diff.json")
	raw, err := os.ReadFile(path)
	if err != nil {
		t.Skipf("storage-compat reference %s not present (standalone checkout): %v", path, err)
	}
	var golden storageTreeGolden
	if err := json.Unmarshal(raw, &golden); err != nil {
		t.Fatalf("parse %s: %v", path, err)
	}
	// A one-sided file means the reference run itself diverged; fail loudly
	// instead of silently comparing against half a contract.
	if len(golden.OnlyPy) != 0 || len(golden.OnlyGo) != 0 || len(golden.DirsOnlyPy) != 0 || len(golden.DirsOnlyGo) != 0 {
		t.Fatalf("%s records one-sided entries (only_py=%v only_go=%v dirs_only_py=%v dirs_only_go=%v)",
			path, golden.OnlyPy, golden.OnlyGo, golden.DirsOnlyPy, golden.DirsOnlyGo)
	}
	return golden
}

func (golden storageTreeGolden) wantFiles() []string {
	files := append(append([]string{}, golden.Equal...), golden.ChangedOpaque...)
	sort.Strings(files)
	return files
}

func assertStorageTreeMatchesGolden(t *testing.T, tree storageHomeTree, golden storageTreeGolden) {
	t.Helper()
	if got, want := tree.fileNames(), golden.wantFiles(); !reflect.DeepEqual(got, want) {
		missing, extra := diffStringSets(want, got)
		t.Fatalf("post-migration files differ from storage-compat reference\nmissing: %v\nextra: %v", missing, extra)
	}
	if want := append([]string{}, golden.PyDirs...); !reflect.DeepEqual(tree.dirs, sortStrings(want)) {
		missing, extra := diffStringSets(want, tree.dirs)
		t.Fatalf("post-migration dirs differ from storage-compat reference\nmissing: %v\nextra: %v", missing, extra)
	}
}

// assertStorageContentPreserved checks that a migrated file kept the exact
// bytes it had at its pre-migration path (the migration moves directories;
// it must not rewrite session/state/conversation fields).
func assertStorageContentPreserved(t *testing.T, before, after storageHomeTree, moves map[string]string) {
	t.Helper()
	for src, dst := range moves {
		sum, ok := before.files[src]
		if !ok {
			t.Errorf("pre-migration file %s not found", src)
			continue
		}
		got, ok := after.files[dst]
		if !ok {
			t.Errorf("migrated file %s -> %s not found", src, dst)
			continue
		}
		if got != sum {
			t.Errorf("migrated file %s -> %s changed content", src, dst)
		}
	}
}

func diffStringSets(want, got []string) (missing, extra []string) {
	wantSet := make(map[string]bool, len(want))
	for _, item := range want {
		wantSet[item] = true
	}
	gotSet := make(map[string]bool, len(got))
	for _, item := range got {
		gotSet[item] = true
		if !wantSet[item] {
			extra = append(extra, item)
		}
	}
	for _, item := range want {
		if !gotSet[item] {
			missing = append(missing, item)
		}
	}
	return missing, extra
}

func sortStrings(values []string) []string {
	sort.Strings(values)
	return values
}

// Parity-exempt: no upstream unit test covers SessionManager's startup storage
// prep; the storage-compat double run is the reference behavior.
func TestStorageStartupMigrationsEmptyHome(t *testing.T) {
	home := t.TempDir()
	var warnings []string
	ensured := RunStorageStartupMigrations(hivehome.Home{Root: home}, func(msg string) {
		warnings = append(warnings, msg)
	})
	if len(warnings) != 0 {
		t.Fatalf("empty home warnings = %v, want none", warnings)
	}
	if len(ensured) != 0 {
		t.Fatalf("empty home ensured trackers = %v, want none", ensured)
	}
	// migrate_v2's predicate is "marker absent", so a fresh home gets the v2
	// marker; v3 and colony_sessions detect nothing to migrate and stay quiet
	// (their markers appear only when a real migration ran).
	tree := walkStorageHome(t, home)
	if got, want := tree.fileNames(), []string{".migrated-v2"}; !reflect.DeepEqual(got, want) {
		t.Fatalf("empty-home files = %v, want %v", got, want)
	}
	if len(tree.dirs) != 0 {
		t.Fatalf("empty-home dirs = %v, want none", tree.dirs)
	}
	raw, err := os.ReadFile(filepath.Join(home, ".migrated-v2"))
	if err != nil {
		t.Fatalf("read .migrated-v2: %v", err)
	}
	if string(raw) != "1\n" {
		t.Fatalf(".migrated-v2 = %q, want %q", raw, "1\n")
	}
}

// Parity-exempt: no upstream unit test covers SessionManager's startup storage
// prep; the storage-compat double run is the reference behavior.
func TestStorageStartupMigrationsV1Home(t *testing.T) {
	home := buildStorageFixture(t, "v1")
	golden := loadStorageTreeGolden(t, "v1")
	before := walkStorageHome(t, home)

	var warnings []string
	ensured := RunStorageStartupMigrations(hivehome.Home{Root: home}, func(msg string) {
		warnings = append(warnings, msg)
	})
	if len(warnings) != 0 {
		t.Fatalf("v1 migration warnings = %v, want none", warnings)
	}
	if len(ensured) != 2 {
		t.Fatalf("v1 ensured trackers = %v, want 2 (colony + .migrations)", ensured)
	}
	tree := walkStorageHome(t, home)
	assertStorageTreeMatchesGolden(t, tree, golden)
	// Moves preserve bytes, so every migrated JSON/Markdown field survives.
	assertStorageContentPreserved(t, before, tree, map[string]string{
		"exports/legacy_colony/metadata.json":                                    "colonies/legacy_colony/metadata.json",
		"exports/legacy_colony/worker.json":                                      "colonies/legacy_colony/worker.json",
		"queen/session/session_20260101_000001_aaaaaaaa/state.json":              "queens/default/sessions/session_20260101_000001_aaaaaaaa/state.json",
		"queen/session/session_20260101_000001_aaaaaaaa/conversations/meta.json": "queens/default/sessions/session_20260101_000001_aaaaaaaa/conversations/meta.json",
		"queen/global_memory/global.md":                                          "memories/global/global.md",
	})

	for _, rel := range []string{
		".migrated-v2",
		".migrated-v3",
		"colonies/.migrations/colony_sessions_v1",
		"colonies/legacy_colony/metadata.json",
		"colonies/legacy_colony/tracker/tracker.db",
		"memories/global/global.md",
		"memories/global/work.md",
		"queens/default/sessions/session_20260101_000001_aaaaaaaa/state.json",
	} {
		if _, ok := tree.files[rel]; !ok {
			t.Errorf("v1 migration missing %s", rel)
		}
	}
	if _, ok := tree.files["queen/session/session_20260101_000001_aaaaaaaa/state.json"]; ok {
		t.Error("v1 migration left the old queen/ tree in place")
	}
	assertNoPendingMigrations(t, home)
}

