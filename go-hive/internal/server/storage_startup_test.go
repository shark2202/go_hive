// Parity-exempt: no upstream unit test covers SessionManager's startup storage
// prep; idempotency of the second startup is a Go-side wiring invariant.
func TestStorageStartupMigrationsSecondStartUnchanged(t *testing.T) {
	home := buildStorageFixture(t, "v2")
	warn := func(msg string) { t.Fatalf("unexpected warning: %s", msg) }
	RunStorageStartupMigrations(hivehome.Home{Root: home}, warn)
	first := walkStorageHome(t, home)

	RunStorageStartupMigrations(hivehome.Home{Root: home}, warn)
	second := walkStorageHome(t, home)

	if got, want := second.fileNames(), first.fileNames(); !reflect.DeepEqual(got, want) {
		t.Fatalf("second startup changed the file inventory\nfirst: %v\nsecond: %v", want, got)
	}
	if !reflect.DeepEqual(second.dirs, first.dirs) {
		t.Fatalf("second startup changed the directory inventory\nfirst: %v\nsecond: %v", first.dirs, second.dirs)
	}
	// The always-on tracker backfill re-opens every tracker.db (upstream's
	// ensure_tracker_db prunes on each startup), so only non-SQLite bytes must
	// stay identical; every migrated JSON/Markdown file is frozen.
	for rel, sum := range first.files {
		if strings.HasSuffix(rel, ".db") || strings.HasSuffix(rel, ".db-wal") || strings.HasSuffix(rel, ".db-shm") {
			continue
		}
		if second.files[rel] != sum {
			t.Errorf("second startup rewrote %s", rel)
		}
	}
	assertNoPendingMigrations(t, home)
}

// Parity-exempt: failure injection around the startup migration sequence is a
// Go-side wiring invariant (upstream only has the try/except warning blocks).
func TestStorageStartupMigrationsFailuresAreNonFatal(t *testing.T) {
	home := t.TempDir()
	injected := errors.New("injected failure")
	var calls []string
	var warnings []string
	steps := storageMigrationSteps{
		migrateV2: func(homeRoot, exportsDir string) error {
			calls = append(calls, "v2:"+exportsDir)
			return injected
		},
		migrateV3: func(homeRoot string) error {
			calls = append(calls, "v3")
			return injected
		},
		migrateColonies: func(homeRoot string) error {
			calls = append(calls, "colony_sessions")
			return injected
		},
		ensureTrackers: func(coloniesDir string) ([]string, error) {
			calls = append(calls, "tracker")
			return []string{"ensured.db"}, injected
		},
	}

	ensured := runStorageStartupMigrations(hivehome.Home{Root: home}, func(msg string) {
		warnings = append(warnings, msg)
	}, steps)

	wantCalls := []string{"v2:" + filepath.Join(home, "exports"), "v3", "colony_sessions", "tracker"}
	if !reflect.DeepEqual(calls, wantCalls) {
		t.Fatalf("step order = %v, want %v", calls, wantCalls)
	}
	wantWarnings := []string{
		"v2 migration failed (non-fatal): injected failure",
		"v3 migration failed (non-fatal): injected failure",
		"colony_sessions migration failed (non-fatal): injected failure",
		"tracker_db: backfill at startup failed (non-fatal): injected failure",
	}
	if len(warnings) != len(wantWarnings) {
		t.Fatalf("warnings = %v, want %v", warnings, wantWarnings)
	}
	for i, want := range wantWarnings {
		if warnings[i] != want {
			t.Errorf("warning[%d] = %q, want %q", i, warnings[i], want)
		}
	}
	if !reflect.DeepEqual(ensured, []string{"ensured.db"}) {
		t.Fatalf("ensured = %v, want the partial tracker result", ensured)
	}
}

// Parity-exempt: failure injection around the startup migration sequence is a
// Go-side wiring invariant (upstream only has the try/except warning blocks).
func TestStorageStartupMigrationsRealFailureIsNonFatal(t *testing.T) {
	home := buildStorageFixture(t, "v1")
	before := walkStorageHome(t, home)
	// A read-only home makes migrate_v2 fail at its marker write (the real
	// error path: the data moves cannot create their targets either); serve
	// must warn and keep going instead of aborting startup.
	if err := os.Chmod(home, 0o555); err != nil {
		t.Fatalf("chmod home read-only: %v", err)
	}
	t.Cleanup(func() { _ = os.Chmod(home, 0o755) })

	var warnings []string
	ensured := RunStorageStartupMigrations(hivehome.Home{Root: home}, func(msg string) {
		warnings = append(warnings, msg)
	})
	if len(ensured) != 0 {
		t.Fatalf("ensured = %v, want none", ensured)
	}
	if len(warnings) != 1 || !strings.Contains(warnings[0], "v2 migration failed (non-fatal)") {
		t.Fatalf("warnings = %v, want exactly the non-fatal v2 warning", warnings)
	}
	after := walkStorageHome(t, home)
	// The failed run must not have "completed" any migration: no v2 marker,
	// no v3/colony markers, and the exports source is still intact. (A
	// mid-failure cleanup can drop files it manages to reach — upstream's
	// shutil.rmtree behaves the same — so only the source is asserted.)
	for _, marker := range []string{".migrated-v2", ".migrated-v3"} {
		if _, ok := after.files[marker]; ok {
			t.Errorf("%s written despite the failure", marker)
		}
	}
	for rel := range before.files {
		if !strings.HasPrefix(rel, "exports/") {
			continue
		}
		if _, ok := after.files[rel]; !ok {
			t.Errorf("exports source %s vanished despite the failed migration", rel)
		}
	}
}

func assertNoPendingMigrations(t *testing.T, home string) {
	t.Helper()
	if storage.NeedsMigrationV2(home) {
		t.Error("NeedsMigrationV2 is still true after startup")
	}
	if storage.NeedsMigrationV3(home) {
		t.Error("NeedsMigrationV3 is still true after startup")
	}
	if storage.NeedsMigrationColonySessions(home) {
		t.Error("NeedsMigrationColonySessions is still true after startup")
	}
}
