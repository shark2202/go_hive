// Storage-startup wiring tests. Upstream has no unit test for the storage prep
// that SessionManager.__init__ runs (grep core/tests core/framework for
// migrate_v2/migrate_v3/migrate_colony_sessions finds only module imports);
// the reference behavior is the storage-verbatim double run
// (`go_hive/scripts/storage_compat_run.sh`), whose post-migration inventory is
// committed under docs/storage-compat/*-tree-diff.json. These tests drive the
// same generated fixtures through the startup wiring and assert the resulting
// tree equals that recorded reference.

