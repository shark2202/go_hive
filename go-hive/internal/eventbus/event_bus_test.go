// Parity: tests/test_event_bus.py::test_cell_survives_ring_buffer_eviction
func TestLoopStateCellSurvivesEviction(t *testing.T) {
	bus := NewEventBus(WithMaxHistory(4))
	bus.Publish(loopStateEvent("awaiting_user", "queen", "turn_done", nil))
	for i := 0; i < 10; i++ {
		tool := NewAgentEvent(EventToolCallStarted, "queen")
		tool.Data = map[string]any{"tool_use_id": "t" + itoa(i), "tool_name": "noop"}
		bus.Publish(tool)
	}

	bus.mu.Lock()
	foundLoopState := false
	for _, event := range bus.history {
		if event.Type == EventLoopStateChanged {
			foundLoopState = true
		}
	}
	bus.mu.Unlock()
	if foundLoopState {
		t.Fatal("loop_state_changed still in history")
	}

	snap := ComputeSessionSnapshot(bus)
	if snap["activity"] != "awaiting_user" {
		t.Fatalf("activity = %#v", snap["activity"])
	}
	if !snapshotBoolField(t, snap, "awaiting_input") {
		t.Fatal("awaiting_input = false")
	}
	if snap["park_reason"] != "turn_done" {
		t.Fatalf("park_reason = %#v", snap["park_reason"])
	}
}

