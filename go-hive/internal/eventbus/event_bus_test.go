// Parity: tests/test_event_bus.py::test_max_concurrent_handlers_respected
func TestMaxConcurrentHandlersRespected(t *testing.T) {
	bus := NewEventBus(WithMaxConcurrentHandlers(2))
	var mu sync.Mutex
	concurrent := 0
	maxConcurrent := 0

	slowHandler := func(*AgentEvent) {
		mu.Lock()
		concurrent++
		if concurrent > maxConcurrent {
			maxConcurrent = concurrent
		}
		mu.Unlock()
		time.Sleep(20 * time.Millisecond)
		mu.Lock()
		concurrent--
		mu.Unlock()
	}
	for i := 0; i < 5; i++ {
		bus.Subscribe([]EventType{EventExecutionStarted}, slowHandler)
	}

	bus.Publish(NewAgentEvent(EventExecutionStarted, "test"))

	mu.Lock()
	defer mu.Unlock()
	if maxConcurrent > 2 {
		t.Fatalf("max concurrent = %d, want <= 2", maxConcurrent)
	}
}

