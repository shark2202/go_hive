type recorder struct {
	mu     sync.Mutex
	events []*AgentEvent
	strs   []string
}

func (r *recorder) addEvent(event *AgentEvent) {
	r.mu.Lock()
	defer r.mu.Unlock()
	r.events = append(r.events, event)
}

func (r *recorder) addString(value string) {
	r.mu.Lock()
	defer r.mu.Unlock()
	r.strs = append(r.strs, value)
}

func (r *recorder) eventSnapshot() []*AgentEvent {
	r.mu.Lock()
	defer r.mu.Unlock()
	out := make([]*AgentEvent, len(r.events))
	copy(out, r.events)
	return out
}

func (r *recorder) stringSnapshot() []string {
	r.mu.Lock()
	defer r.mu.Unlock()
	out := make([]string, len(r.strs))
	copy(out, r.strs)
	return out
}

