#!/usr/bin/env python3
"""Generate go-hive/internal/credentials/specs_gen.go from the upstream registry.

The Python reference implementation lives in ``tools/src/aden_tools/credentials``
(85 modules today). Each module exports one ``<CATEGORY>_CREDENTIALS`` dict of
``credential name -> CredentialSpec``; ``__init__.py`` merges most of them into
``CREDENTIAL_SPECS``. This script reads those modules with ``ast`` (no import,
no third-party dependency) and projects every distinct ``credential_id`` onto a
pure-Go data table so the Go server can serve the same catalogue as the
reference server.

Usage, from the repository root:

    uv run --no-project python go_hive/scripts/gen_credential_specs.py
    uv run --no-project python go_hive/scripts/gen_credential_specs.py --check

``--check`` regenerates in memory and exits non-zero when the checked-in file is
stale. Only the Python standard library is used.
"""

from __future__ import annotations

import argparse
import ast
import hashlib
import json
import shutil
import subprocess
import sys
from collections import defaultdict
from pathlib import Path

SOURCE_PACKAGE = Path("tools/src/aden_tools/credentials")
TOOL_PACKAGE = Path("tools/src/aden_tools/tools")
OUTPUT_FILE = Path("go_hive/go-hive/internal/credentials/specs_gen.go")

# Calls on a credential manager whose first positional argument names a spec.
CREDENTIAL_LOOKUPS = {
    "get",
    "get_by_alias",
    "is_available",
    "get_spec",
    "get_secret",
    "require",
    "resolve",
    "resolve_headers",
}
# Calls whose first positional argument names an environment variable.
ENV_LOOKUPS = {"getenv", "getenv_default", "environ_get"}

GO_HEADER = """\
// Code generated by go_hive/scripts/gen_credential_specs.py; DO NOT EDIT.
//
// Source: {package} ({module_count} modules, {spec_count} credential ids).
// Regenerate with:
//   uv run --no-project python go_hive/scripts/gen_credential_specs.py
// The source digest below makes a stale table detectable.
//
// Parity: tools/src/aden_tools/credentials/base.py::CredentialSpec

package credentials
"""


def repo_root() -> Path:
    """Return the repository root that contains the Python reference package."""
    here = Path(__file__).resolve()
    for candidate in here.parents:
        if (candidate / SOURCE_PACKAGE).is_dir():
            return candidate
    raise SystemExit(f"gen_credential_specs: cannot locate {SOURCE_PACKAGE} above {here}")


def literal(node: ast.AST | None, *, allow_tuple: bool = False) -> object | None:
    """Evaluate a literal AST node, returning None when it is not static."""
    if node is None:
        return None
    try:
        value = ast.literal_eval(node)
    except (ValueError, SyntaxError):
        return None
    if allow_tuple and isinstance(value, (list, tuple)):
        return list(value)
    return value


def merged_category_names(init_path: Path) -> set[str]:
    """Category names (``FOO`` for ``FOO_CREDENTIALS``) merged into CREDENTIAL_SPECS."""
    tree = ast.parse(init_path.read_text(encoding="utf-8"))
    merged: set[str] = set()
    for node in tree.body:
        if not isinstance(node, ast.Assign):
            continue
        targets = [t.id for t in node.targets if isinstance(t, ast.Name)]
        if "CREDENTIAL_SPECS" not in targets or not isinstance(node.value, ast.Dict):
            continue
        for key, value in zip(node.value.keys, node.value.values):
            # ``{**FOO_CREDENTIALS}`` parses as key=None, value=Name("FOO_CREDENTIALS").
            name = None
            if key is None and isinstance(value, ast.Name):
                name = value.id
            elif isinstance(key, ast.Name):
                name = key.id
            if name is not None and name.endswith("_CREDENTIALS"):
                merged.add(name[: -len("_CREDENTIALS")])
    if not merged:
        raise SystemExit(f"gen_credential_specs: no merged categories found in {init_path}")
    return merged


def credential_dicts(tree: ast.Module):
    """Yield ``(category, dict_node)`` for top-level ``*_CREDENTIALS`` literals."""
    for node in tree.body:
        target_name = None
        value_node = None
        if isinstance(node, ast.Assign):
            value_node = node.value
            names = [t.id for t in node.targets if isinstance(t, ast.Name)]
            target_name = names[0] if names else None
        elif isinstance(node, ast.AnnAssign) and isinstance(node.target, ast.Name):
            value_node = node.value
            target_name = node.target.id
        if target_name is None or not target_name.endswith("_CREDENTIALS"):
            continue
        if not isinstance(value_node, ast.Dict):
            continue
        yield target_name[: -len("_CREDENTIALS")], value_node


def module_constants(tree: ast.Module) -> dict[str, object]:
    """Collect module-level names bound to literal values (e.g. ``_X_TOOLS``)."""
    constants: dict[str, object] = {}
    for node in tree.body:
        value_node = None
        targets: list[str] = []
        if isinstance(node, ast.Assign):
            value_node = node.value
            targets = [t.id for t in node.targets if isinstance(t, ast.Name)]
        elif isinstance(node, ast.AnnAssign) and isinstance(node.target, ast.Name):
            value_node = node.value
            targets = [node.target.id]
        if value_node is None:
            continue
        value = literal(value_node, allow_tuple=True)
        if value is None:
            continue
        for target in targets:
            constants[target] = value
    return constants


def spec_fields(call: ast.AST, constants: dict[str, object] | None = None) -> dict[str, object]:
    """Extract CredentialSpec(...) keyword arguments that are static literals."""
    fields: dict[str, object] = {}
    if not isinstance(call, ast.Call):
        return fields
    for keyword in call.keywords:
        if keyword.arg is None:
            continue
        value = literal(keyword.value, allow_tuple=True)
        if value is None and constants and isinstance(keyword.value, ast.Name):
            # ``tools=_X_TOOLS`` points at a module-level list.
            value = constants.get(keyword.value.id)
        if value is None:
            continue
        fields[keyword.arg] = value
    return fields


def collect_specs(package: Path) -> tuple[list[dict[str, object]], int, set[str]]:
    """Read every credential module and return raw spec candidates."""
    merged = merged_category_names(package / "__init__.py")
    entries: list[dict[str, object]] = []
    modules = len(list(package.glob("*.py")))
    for path in sorted(package.glob("*.py")):
        if path.name.startswith("_"):
            continue
        tree = ast.parse(path.read_text(encoding="utf-8"))
        constants = module_constants(tree)
        for category, dict_node in credential_dicts(tree):
            for key_node, value_node in zip(dict_node.keys, dict_node.values):
                name = literal(key_node)
                if not isinstance(name, str) or not name:
                    continue
                fields = spec_fields(value_node, constants)
                fields.setdefault("env_var", "")
                entries.append(
                    {
                        "name": name,
                        "category": category,
                        "module": path.name,
                        "merged": category in merged,
                        "fields": fields,
                    }
                )
    return entries, modules, merged


def scan_tool_modules(tool_root: Path) -> dict[str, set[str]]:
    """Map every credential name / env var to the tool modules that read it."""
    usage: dict[str, set[str]] = defaultdict(set)
    if not tool_root.is_dir():
        return usage
    for path in sorted(tool_root.rglob("*.py")):
        if path.name.startswith("_"):
            continue
        try:
            tree = ast.parse(path.read_text(encoding="utf-8"))
        except SyntaxError:
            continue
        package = path.relative_to(tool_root).parts[0]
        label = package if len(path.relative_to(tool_root).parts) > 1 else path.stem
        for node in ast.walk(tree):
            if isinstance(node, ast.Call) and isinstance(node.func, ast.Attribute):
                attribute = node.func.attr
                if attribute not in CREDENTIAL_LOOKUPS | ENV_LOOKUPS:
                    continue
                if not node.args:
                    continue
                value = literal(node.args[0])
                if isinstance(value, str) and value:
                    usage[value].add(label)
            elif isinstance(node, ast.Subscript) and isinstance(node.value, ast.Attribute):
                # os.environ["KEY"]
                if node.value.attr != "environ":
                    continue
                value = literal(node.slice)
                if isinstance(value, str) and value:
                    usage[value].add(label)
    return usage


def select_specs(entries: list[dict[str, object]]) -> list[dict[str, object]]:
    """Deduplicate by credential_id, preferring the merged canonical module."""
    by_id: dict[str, list[dict[str, object]]] = defaultdict(list)
    for entry in entries:
        fields = entry["fields"]  # type: ignore[index]
        credential_id = str(fields.get("credential_id") or "")  # type: ignore[union-attr]
        if not credential_id:
            credential_id = str(entry["name"])
        entry["credential_id"] = credential_id
        by_id[credential_id].append(entry)

    selected: list[dict[str, object]] = []
    for credential_id in sorted(by_id):
        candidates = by_id[credential_id]
        # Merged categories are the runtime registry; unmerged modules (x.py,
        # zoho.py, integrations.py) are fallbacks. Break remaining ties
        # deterministically by module file name.
        candidates.sort(
            key=lambda entry: (
                not bool(entry["merged"]),
                str(entry["module"]),
                str(entry["name"]),
            )
        )
        selected.append(candidates[0])
    return selected


def build_rows(selected: list[dict[str, object]], usage: dict[str, set[str]]) -> list[dict[str, object]]:
    """Project selected specs onto the row shape emitted into Go."""
    rows: list[dict[str, object]] = []
    for entry in selected:
        fields = entry["fields"]  # type: ignore[index]
        assert isinstance(fields, dict)
        name = str(entry["name"])
        env_var = str(fields.get("env_var") or "")
        tool_modules = set(usage.get(name, set()))
        if env_var:
            tool_modules |= usage.get(env_var, set())
        rows.append(
            {
                "name": name,
                "credential_id": entry["credential_id"],
                "env_var": env_var,
                "description": str(fields.get("description") or ""),
                "help_url": str(fields.get("help_url") or ""),
                "api_key_instructions": str(fields.get("api_key_instructions") or ""),
                "tools": [str(value) for value in (fields.get("tools") or [])],
                "node_types": [str(value) for value in (fields.get("node_types") or [])],
                "tool_modules": sorted(tool_modules),
                "aden_supported": bool(fields.get("aden_supported", False)),
                "aden_provider_name": str(fields.get("aden_provider_name") or ""),
                "direct_api_key_supported": bool(fields.get("direct_api_key_supported", True)),
                "required": bool(fields.get("required", True)),
                "startup_required": bool(fields.get("startup_required", False)),
                "credential_key": str(fields.get("credential_key") or "access_token"),
                "credential_group": str(fields.get("credential_group") or ""),
                "health_check_endpoint": str(fields.get("health_check_endpoint") or ""),
                "health_check_method": str(fields.get("health_check_method") or "GET"),
                "source_module": str(entry["module"]),
            }
        )
    return rows


def source_digest(rows: list[dict[str, object]], module_count: int) -> str:
    payload = json.dumps(
        {"modules": module_count, "rows": rows},
        sort_keys=True,
        separators=(",", ":"),
        ensure_ascii=False,
    ).encode("utf-8")
    return hashlib.sha256(payload).hexdigest()


def go_string(value: str) -> str:
    """Render a Go interpreted string literal."""
    return json.dumps(value, ensure_ascii=False)


def go_string_slice(values: list[str]) -> str:
    if not values:
        return "nil"
    return "[]string{" + ", ".join(go_string(value) for value in values) + "}"


def render(rows: list[dict[str, object]], module_count: int, digest: str) -> str:
    out: list[str] = [
        GO_HEADER.format(
            package=SOURCE_PACKAGE.as_posix(),
            module_count=module_count,
            spec_count=len(rows),
        ),
        "",
        "// GeneratedSpecsDigest fingerprints the upstream registry this table was",
        "// generated from. A mismatch means the table is stale: regenerate it.",
        f"const GeneratedSpecsDigest = {go_string(digest)}",
        "",
        "// GeneratedSpecsModuleCount is the number of upstream credential modules read.",
        f"const GeneratedSpecsModuleCount = {module_count}",
        "",
        "// GeneratedCredentialSpec is the Go projection of one upstream CredentialSpec.",
        "type GeneratedCredentialSpec struct {",
        "\tName string",
        "\tCredentialID string",
        "\tEnvVar string",
        "\tDescription string",
        "\tHelpURL string",
        "\tAPIKeyInstructions string",
        "\tTools []string",
        "\tNodeTypes []string",
        "\tToolModules []string",
        "\tAdenSupported bool",
        "\tAdenProviderName string",
        "\tDirectAPIKeySupported bool",
        "\tRequired bool",
        "\tStartupRequired bool",
        "\tCredentialKey string",
        "\tCredentialGroup string",
        "\tHealthCheckEndpoint string",
        "\tHealthCheckMethod string",
        "\tSourceModule string",
        "}",
        "",
        "// GeneratedCredentialSpecs lists every credential declared by the upstream",
        "// registry, ordered by credential id.",
        "var GeneratedCredentialSpecs = []GeneratedCredentialSpec{",
    ]
    for row in rows:
        out.append("\t{")
        for field, key in (
            ("Name", "name"),
            ("CredentialID", "credential_id"),
            ("EnvVar", "env_var"),
            ("Description", "description"),
            ("HelpURL", "help_url"),
            ("APIKeyInstructions", "api_key_instructions"),
        ):
            out.append(f"\t\t{field}: {go_string(str(row[key]))},")
        for field, key in (("Tools", "tools"), ("NodeTypes", "node_types"), ("ToolModules", "tool_modules")):
            values = row[key]
            assert isinstance(values, list)
            out.append(f"\t\t{field}: {go_string_slice([str(v) for v in values])},")
        for field, key in (
            ("AdenSupported", "aden_supported"),
            ("DirectAPIKeySupported", "direct_api_key_supported"),
            ("Required", "required"),
            ("StartupRequired", "startup_required"),
        ):
            out.append(f"\t\t{field}: {str(bool(row[key])).lower()},")
        for field, key in (
            ("AdenProviderName", "aden_provider_name"),
            ("CredentialKey", "credential_key"),
            ("CredentialGroup", "credential_group"),
            ("HealthCheckEndpoint", "health_check_endpoint"),
            ("HealthCheckMethod", "health_check_method"),
            ("SourceModule", "source_module"),
        ):
            out.append(f"\t\t{field}: {go_string(str(row[key]))},")
        out.append("\t},")
    out.append("}")
    out.append("")
    return "\n".join(out)


def gofmt(text: str) -> str:
    """Format the generated source with gofmt so a fresh run is stable."""
    gofmt_bin = shutil.which("gofmt")
    if gofmt_bin is None:
        print("gen_credential_specs: gofmt not found, emitting unformatted source", file=sys.stderr)
        return text
    result = subprocess.run(
        [gofmt_bin],
        input=text,
        text=True,
        capture_output=True,
        check=False,
    )
    if result.returncode != 0:
        print(f"gen_credential_specs: gofmt failed: {result.stderr.strip()}", file=sys.stderr)
        return text
    return result.stdout


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Generate specs_gen.go from the Python credential registry.")
    parser.add_argument("--check", action="store_true", help="verify the checked-in file is up to date")
    parser.add_argument("--output", type=Path, default=None, help="override the output path")
    args = parser.parse_args(argv)

    root = repo_root()
    entries, module_count, _ = collect_specs(root / SOURCE_PACKAGE)
    selected = select_specs(entries)
    usage = scan_tool_modules(root / TOOL_PACKAGE)
    rows = build_rows(selected, usage)
    digest = source_digest(rows, module_count)
    rendered = gofmt(render(rows, module_count, digest))

    output = args.output or (root / OUTPUT_FILE)
    if args.check:
        existing = output.read_text(encoding="utf-8") if output.exists() else ""
        if existing != rendered:
            print(f"gen_credential_specs: STALE — {output} does not match upstream", file=sys.stderr)
            return 1
        print(f"gen_credential_specs: OK — {len(rows)} specs match upstream ({digest[:12]})")
        return 0

    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(rendered, encoding="utf-8")
    with_modules = sum(1 for row in rows if row["tool_modules"])
    print(
        f"gen_credential_specs: wrote {output} — {len(rows)} credential ids "
        f"from {module_count} modules ({with_modules} with tool modules), digest {digest[:12]}"
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
