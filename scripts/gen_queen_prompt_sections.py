#!/usr/bin/env python3
"""Generate the Go queen static prompt from the Python reference.

The queen's system prompt is text, and text drifts silently: a re-typed
paragraph, a lost blank line, a smart quote turned into ASCII all change what
the model sees without failing any build. This generator removes the
transcription step entirely -- it imports the upstream node module and emits
``go-hive/internal/queen/prompt_sections.go`` with every section as the exact
string upstream computes for this build.

Source of truth (upstream):

    core/framework/agents/queen/nodes/__init__.py
      _queen_character_core / _queen_role_independent / _queen_tools_independent
      _queen_behavior_always / _queen_behavior_independent
      _queen_role_colony / _queen_tools_colony / _queen_behavior_colony

    core/framework/orchestrator/prompting.py
      build_credentials_summary

Phase composition (upstream queen_orchestrator.py):

    INDEPENDENT = character_core + role_independent + tools_independent
                  + behavior_always + behavior_independent
    COLONY      = character_core + role_colony + tools_colony
                  + behavior_colony + behavior_always

It also writes the frozen goldens under
``go-hive/internal/queen/testdata/prompt/`` (the phase prompts, the credentials
block variants) so the Go tests compare against upstream-rendered text rather
than against a re-typed expectation.

Usage, from the repository root:

    uv run --offline python go_hive/scripts/gen_queen_prompt_sections.py
    uv run --offline python go_hive/scripts/gen_queen_prompt_sections.py --check

``--check`` regenerates in memory and exits non-zero when either the Go file or
a golden is stale, so a drift is caught without touching the worktree.

Only the Python standard library is used beyond the repository's own package.
"""

from __future__ import annotations

import argparse
import difflib
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[2]
CORE_ROOT = REPO_ROOT / "core"
GO_MODULE = REPO_ROOT / "go_hive" / "go-hive"
GO_OUTPUT = GO_MODULE / "internal" / "queen" / "prompt_sections.go"
GOLDEN_DIR = GO_MODULE / "internal" / "queen" / "testdata" / "prompt"
# The live parity probe's capture of the Python reference's first-turn system
# prompt. The full-prompt golden below is re-derived from the module state and
# cross-checked against this capture, so the Go test pins the exact text the
# reference actually sent, not just what the modules say they would send.
PARITY_CAPTURE = REPO_ROOT / "go_hive" / "docs" / "e2e-assets" / "prompt-catalog" / "system-prompt.python.txt"
PARITY_PROBE_QUEEN = "queen_growth"
SERVER_GOLDEN = GO_MODULE / "internal" / "server" / "testdata" / "prompt" / "queen_growth.independent.python.txt"

GO_HEADER = """// Code generated by go_hive/scripts/gen_queen_prompt_sections.py from
// core/framework/agents/queen/nodes/__init__.py and
// core/framework/orchestrator/prompting.py. DO NOT EDIT.
//
// Each constant is the byte-exact value the Python reference computes for this
// build: the phase-specific segments of the queen's static system prompt plus
// the ambient credentials block. Regenerate with
//
//     uv run --offline python go_hive/scripts/gen_queen_prompt_sections.py
//
// after any upstream edit, and re-run the prompt parity probe
// (go_hive/scripts/prompt_system_parity.py) to confirm the live request bodies
// still match section by section.

package queen
"""

# Patterns upstream resolves at prompt-build time instead of shipping verbatim:
# a vision-only block is kept for vision models and dropped for text-only ones.
# Neither ship today, so the vision flag cannot change these sections; if one
# appears the generator stops rather than silently picking a variant.
VISION_ONLY_MARKERS = ("<!-- vision-only -->", "<!-- /vision-only -->")


def go_quoted_line(line: str, newline: bool) -> str:
    """One Go interpreted-string literal for one logical line."""
    out = ['"']
    for char in line:
        if char == "\\":
            out.append("\\\\")
        elif char == '"':
            out.append('\\"')
        elif char == "\t":
            out.append("\\t")
        elif char == "\r":
            out.append("\\r")
        else:
            out.append(char)
    if newline:
        out.append("\\n")
    out.append('"')
    return "".join(out)


def go_const(name: str, doc: str, value: str) -> str:
    """Emit one constant as per-line continuations.

    Upstream's segments are prose with deliberate blank lines and wrapping; one
    literal per source line keeps a diff reviewable in the same shape as the
    Python source instead of one 13 KB line.
    """
    lines = value.split("\n")
    literals = [go_quoted_line(line, index < len(lines) - 1) for index, line in enumerate(lines)]
    if not literals:
        return f"// {doc}\nconst {name} = \"\"\n"
    first, rest = literals[0], literals[1:]
    rendered = f"const {name} = {first}"
    if rest:
        rendered += " +\n" + " +\n".join("\t" + literal for literal in rest)
    return f"// {doc}\n{rendered}\n"


def main() -> int:
    parser = argparse.ArgumentParser(description="Generate the Go queen static prompt from the Python reference.")
    parser.add_argument("--check", action="store_true", help="verify the checked-in files are current")
    args = parser.parse_args()

    sys.path.insert(0, str(CORE_ROOT))

    from framework.agents.queen import nodes as qn  # noqa: PLC0415
    from framework.agents.queen.queen_profiles import format_queen_identity_prompt  # noqa: PLC0415
    from framework.orchestrator.prompting import build_credentials_summary  # noqa: PLC0415

    sections = {
        "queenCharacterCore": qn._queen_character_core,
        "queenRoleIndependent": qn._queen_role_independent,
        "queenToolsIndependent": qn._queen_tools_independent,
        "queenBehaviorAlways": qn._queen_behavior_always,
        "queenBehaviorIndependent": qn._queen_behavior_independent,
        "queenRoleColony": qn._queen_role_colony,
        "queenToolsColony": qn._queen_tools_colony,
        "queenBehaviorColony": qn._queen_behavior_colony,
    }

    # Refuse to guess: a vision-only block means the section is model-dependent
    # and the Go side would need the same capability switch before porting.
    dependents = []
    for name, value in sections.items():
        for marker in VISION_ONLY_MARKERS:
            if marker in value:
                dependents.append(name)
    if dependents:
        raise SystemExit(
            "vision-only blocks appeared in " + ", ".join(sorted(set(dependents))) + "; "
            "implement finalize_queen_prompt(has_vision) on the Go side before generating"
        )

    independent = qn.finalize_queen_prompt(
        sections["queenCharacterCore"]
        + sections["queenRoleIndependent"]
        + sections["queenToolsIndependent"]
        + sections["queenBehaviorAlways"]
        + sections["queenBehaviorIndependent"],
        False,
    )
    colony = qn.finalize_queen_prompt(
        sections["queenCharacterCore"]
        + sections["queenRoleColony"]
        + sections["queenToolsColony"]
        + sections["queenBehaviorColony"]
        + sections["queenBehaviorAlways"],
        False,
    )

    # Phase prompts carry no model-dependent text (asserted above), so the
    # vision variant is the same text; check it instead of assuming it.
    for label, text in (("independent", independent), ("colony", colony)):
        if qn.finalize_queen_prompt(text, True) != text:
            raise SystemExit(f"{label}: vision and text-only variants of the phase prompt differ")

    # The credentials block is code, not a constant: the Go port renders the
    # same two shapes. Goldens pin the exact wording of both.
    sample_accounts = [
        {"provider": "google", "alias": "work", "credential_id": "google"},
        {"provider": "google", "alias": "personal", "credential_id": "google"},
        {"provider": "notion", "alias": "default", "credential_id": "notion"},
        {"alias": "no-provider", "credential_id": "slack"},
    ]
    credentials_none = build_credentials_summary([])
    credentials_some = build_credentials_summary(sample_accounts)

    docs = {
        "queenCharacterCore": "Phase-invariant character core. Parity: nodes/__init__.py::_queen_character_core",
        "queenRoleIndependent": "INDEPENDENT role. Parity: nodes/__init__.py::_queen_role_independent",
        "queenToolsIndependent": "INDEPENDENT tool docs. Parity: nodes/__init__.py::_queen_tools_independent",
        "queenBehaviorAlways": "Shared rules: System Rules + task plan + pivot + file/share/draft + communication + memory. Parity: nodes/__init__.py::_queen_behavior_always",
        "queenBehaviorIndependent": "INDEPENDENT-only behavior. Parity: nodes/__init__.py::_queen_behavior_independent",
        "queenRoleColony": "COLONY role. Parity: nodes/__init__.py::_queen_role_colony",
        "queenToolsColony": "COLONY tool docs. Parity: nodes/__init__.py::_queen_tools_colony",
        "queenBehaviorColony": "COLONY delegation loop + operating rules. Parity: nodes/__init__.py::_queen_behavior_colony",
    }
    order = [
        "queenCharacterCore",
        "queenRoleIndependent",
        "queenToolsIndependent",
        "queenBehaviorIndependent",
        "queenRoleColony",
        "queenToolsColony",
        "queenBehaviorColony",
        "queenBehaviorAlways",
    ]

    go_text = GO_HEADER + "\n" + "\n".join(go_const(name, docs[name], sections[name]) for name in order)

    goldens = {
        "independent.txt": independent,
        "colony.txt": colony,
        "credentials.none.txt": credentials_none,
        "credentials.some.txt": credentials_some,
    }

    # The identity rendering is already ported (internal/queen/identity.go), so
    # the full first-turn prompt is re-derivable here: profile identity + a
    # blank line + the phase prompt + a blank line + the credentials block. The
    # probe home ships no soul (nothing has been reflected yet), so no soul
    # segment. Cross-check it against the live capture when it is present.
    from framework.agents.queen.queen_profiles import load_queen_profile  # noqa: PLC0415

    probe_identity = format_queen_identity_prompt(load_queen_profile(PARITY_PROBE_QUEEN), max_examples=0).strip()
    first_turn = probe_identity + "\n\n" + independent + "\n\n" + credentials_none
    if PARITY_CAPTURE.is_file():
        capture = PARITY_CAPTURE.read_text(encoding="utf-8")
        if capture != first_turn:
            raise SystemExit(
                f"{PARITY_CAPTURE.relative_to(REPO_ROOT)} does not match the re-derived Python prompt "
                f"(capture {len(capture)} chars, derived {len(first_turn)} chars); re-run "
                "go_hive/scripts/prompt_system_parity.py before regenerating"
            )
    else:
        print(f"note: {PARITY_CAPTURE.relative_to(REPO_ROOT)} is absent; skipping the live-capture cross-check")

    outputs: list[tuple[Path, str]] = [
        (GOLDEN_DIR / name, text) for name, text in goldens.items()
    ]
    outputs.append((SERVER_GOLDEN, first_turn))

    stale: list[str] = []
    go_rel = str(GO_OUTPUT.relative_to(REPO_ROOT))
    if not GO_OUTPUT.is_file():
        stale.append(go_rel + " (missing)")
    elif GO_OUTPUT.read_text(encoding="utf-8") != go_text:
        stale.append(go_rel)
    for path, text in outputs:
        if not path.is_file() or path.read_text(encoding="utf-8") != text:
            stale.append(str(path.relative_to(REPO_ROOT)))

    if args.check:
        if stale:
            print("stale generated prompt artifacts:")
            for entry in stale:
                print("  " + entry)
            return 1
        print("queen prompt sections are current")
        return 0

    if stale and GO_OUTPUT.is_file():
        current = GO_OUTPUT.read_text(encoding="utf-8")
        diff = "".join(
            difflib.unified_diff(
                current.splitlines(keepends=True),
                go_text.splitlines(keepends=True),
                fromfile=str(GO_OUTPUT.relative_to(REPO_ROOT)),
                tofile="(regenerated)",
                n=1,
            )
        )
        if diff:
            print(diff, file=sys.stderr)

    GO_OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    GO_OUTPUT.write_text(go_text, encoding="utf-8")
    for path, text in outputs:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8")

    print(f"wrote {GO_OUTPUT.relative_to(REPO_ROOT)} ({len(go_text)} bytes)")
    for name in order:
        print(f"  {len(sections[name]):>6}  {name}")
    print(f"  {len(independent):>6}  independent (composed)")
    print(f"  {len(colony):>6}  colony (composed)")
    print(f"  {len(credentials_none):>6}  credentials.none")
    print(f"  {len(credentials_some):>6}  credentials.some")
    print(f"  {len(first_turn):>6}  {PARITY_PROBE_QUEEN} first turn (independent + credentials)")
    print(f"goldens: {GOLDEN_DIR.relative_to(REPO_ROOT)}, {SERVER_GOLDEN.relative_to(REPO_ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
