def parse_dimensions() -> dict:
    text = MATRIX.read_text()
    rows = re.findall(
        r'<tr><td class="num">\d+</td><td><b>.*?</b>.*?id: <code>(.*?)</code>.*?</tr>',
        text,
        re.S,
    )
    dims = {}
    for block in re.finditer(
        r'<tr><td class="num">\d+</td><td><b>.*?</b>.*?id: <code>(.*?)</code>(.*?)</tr>',
        text,
        re.S,
    ):
        dim, rest = block.group(1), block.group(2)
        pill = re.search(r'<span class="pill [^"]+">(已实测一致|部分对齐|有契约未验证|未对齐|未审计|范围外（声明）)</span>', rest)
        if not pill:
            continue
        label = pill.group(1)
        code = next(k for k, v in STATUS_LABEL.items() if v == label)
        dims[dim] = code
    if len(dims) < 20:
        sys.exit(f"parsed only {len(dims)} dimension statuses from {MATRIX}")
    return dims


def go_packages() -> dict:
    """Live scan of go_hive/go-hive/internal/<pkg> (aggregates subpackages)."""
    root = GO_ROOT / "internal"
    all_prod = [f for f in GO_ROOT.rglob("*.go") if not f.name.endswith("_test.go")]
    stats = {}
    for p in sorted(root.iterdir()):
        if not p.is_dir():
            continue
        name = p.name
        files = [f for f in p.rglob("*.go") if not f.name.endswith("_test.go")]
        tests = [f for f in p.rglob("*_test.go")]
        loc = sum(len(f.read_text(errors="ignore").splitlines()) for f in files)
        parity = sum(len(re.findall(r"// Parity:", f.read_text(errors="ignore"))) for f in tests)
        tfuncs = sum(len(re.findall(r"^func Test", f.read_text(errors="ignore"), re.M)) for f in tests)
        needle = f"github.com/shark2202/go_hive/go-hive/internal/{name}"
        importers = 0
        for f in all_prod:
            if f.is_relative_to(p):
                continue
            txt = f.read_text(errors="ignore")
            if re.search(r'"' + re.escape(needle) + r'"', txt):
                importers += 1
        stats[name] = {
            "package": f"internal/{name}",
            "files": len(files),
            "loc": loc,
            "test_files": len(tests),
            "test_funcs": tfuncs,
            "parity_refs": parity,
            "importers": importers,
        }
    return stats


def read_go_version() -> str:
    path = GO_ROOT / "internal" / "version" / "version.go"
    match = re.search(r'const Version = "([^"]+)"', path.read_text())
    return match.group(1) if match else "unknown"


def _count_lines(files: list[Path]) -> int:
    return sum(len(f.read_text(errors="ignore").splitlines()) for f in files)


