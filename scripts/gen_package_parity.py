def validate_scope(scope: dict) -> None:
    """Fail generation when the scope marker stops being explicit."""
    problems = []
    if scope.get("scope_id") != "core-framework-only":
        problems.append("scope_id must be core-framework-only")
    if scope.get("status") != "not_computed":
        problems.append("integration coverage must stay explicitly not_computed")
    if "unported: 0" not in scope.get("unported_zero_scope", ""):
        problems.append("unported_zero_scope must name the unported: 0 claim")
    if "core/framework" not in scope.get("unported_zero_scope", ""):
        problems.append("unported_zero_scope must name core/framework")
    if scope.get("covered_paths") != ["core/framework"]:
        problems.append("covered_paths must be exactly [core/framework]")
    counts = scope.get("counts", {})
    for key in (
        "aden_tools_python_files",
        "aden_tools_mcp_tools",
        "go_integrations_prod_files",
        "go_integrations_evidence_modules",
    ):
        if int(counts.get(key) or 0) <= 0:
            problems.append(f"counts.{key} must be positive")
    tool_row = next((r for r in scope.get("matrix", []) if r.get("area") == "tools/src/aden_tools"), None)
    if not tool_row or tool_row.get("coverage") != "not_computed":
        problems.append("tools/src/aden_tools row must be present and not_computed")
    for rel in scope.get("excluded_paths", []):
        if not (REPO / rel).exists():
            problems.append(f"excluded path does not exist: {rel}")
    if problems:
        sys.exit("integration scope: " + "; ".join(problems))


def anchor_pkg(anchor: str) -> str | None:
    m = re.search(r"/internal/([a-z0-9_]+)/", anchor or "")
    return m.group(1) if m else None


def attribute(registry: dict, valid_pkgs: set[str]) -> tuple[dict, dict, list]:
    """Return (rows_by_pkg, gaps_by_pkg, all_gaps). A row anchored in several
    packages is counted once per package; consumers dedupe by row id and only
    count the package's primary Python owner."""
    rows_by_pkg: dict[str, list] = {}
    for section in ("synthetic_dispatch", "events", "phase_gates"):
        for row in registry.get(section, []):
            anchors = [row.get("go_anchor") or ""]
            anchors += [a.get("anchor", "") if isinstance(a, dict) else str(a) for a in row.get("go_anchors", [])]
            pkgs: set[str] = set()
            for a in anchors:
                p = anchor_pkg(a)
                if p:
                    pkgs.add(p)
            for pkg in pkgs:
                rows_by_pkg.setdefault(pkg, []).append(
                    {
                        "id": row.get("id"),
                        "section": section,
                        "status": row.get("status"),
                    }
                )
    gaps_by_pkg: dict[str, list] = {}
    all_gaps = []
    for gap in registry.get("known_gaps", []):
        # The gap's owner field names the Go package the fix lands in; prefer
        # it over the anchor file, which can sit in a shared helper package.
        owner = gap.get("owner")
        pkg = owner if owner in valid_pkgs else anchor_pkg(gap.get("go_anchor") or "")
        item = {
            "id": gap.get("id"),
            "title": gap.get("title"),
            "status": gap.get("status"),
            "owner": gap.get("owner"),
            "go_anchor": gap.get("go_anchor"),
            "upstream_anchor": gap.get("upstream_anchor"),
            "notes": gap.get("notes"),
            "package": pkg,
        }
        all_gaps.append(item)
        if pkg:
            gaps_by_pkg.setdefault(pkg, []).append(item)
    return rows_by_pkg, gaps_by_pkg, all_gaps


# port_ungated is a documented systemic difference (Go has no _QUEEN_*_TOOLS
# equivalent), counted separately rather than as a per-package bad row.
BAD_ROW = {"partial", "missing", "builder_only", "go_const_only"}


def compute() -> dict:
    py = load_python()
    reg = load_registry()
    dims = parse_dimensions()
    gos = go_packages()
    go_version = read_go_version()
    c12 = load_c12()
    c12_by_pkg: dict[str, Counter] = {}
    c12_unported = []
    for row in c12.get("files", []):
        counts = c12_by_pkg.setdefault(row.get("domain") or "(root)", Counter())
        counts[row.get("status", "unknown")] += 1
        if row.get("status") == "unported":
            c12_unported.append(
                {
                    "domain": row.get("domain") or "(root)",
                    "path": row.get("python_path"),
                    "basis": row.get("basis"),
                    "kind": row.get("kind"),
                }
            )
    if set(GO_PRIMARY) != set(gos):
        sys.exit(
            "GO_PRIMARY must cover every Go package exactly; "
            f"missing={sorted(set(gos) - set(GO_PRIMARY))} extra={sorted(set(GO_PRIMARY) - set(gos))}"
        )
    scope = integration_scope(len(c12.get("files", [])))
    validate_scope(scope)
    rows_by_pkg, gaps_by_pkg, all_gaps = attribute(reg, set(gos))

    claimed_go: set[str] = set()
    pairs = []
    for spec in PAIRS:
        pyname = spec["py"]
        pyd = py["packages"].get(pyname)
        if pyd is None:
            sys.exit(f"Python package {pyname!r} not in {PY_ATLAS}")
        go_names = spec["go"]
        for g in go_names:
            if g not in gos:
                sys.exit(f"Go package internal/{g} (mapped from {pyname}) does not exist")
            claimed_go.add(g)
        go_rows = [dict(gos[g], name=g) for g in go_names]
        go_files = sum(r["files"] for r in go_rows)
        go_loc = sum(r["loc"] for r in go_rows)
        go_tfuncs = sum(r["test_funcs"] for r in go_rows)
        go_parity = sum(r["parity_refs"] for r in go_rows)
        importers = [r["importers"] for r in go_rows if r["name"] not in UNWIRED_EXEMPT] or [0]
        unwired = [r["name"] for r in go_rows if r["importers"] == 0 and r["name"] not in UNWIRED_EXEMPT]
        unwired_exempt = [r["name"] for r in go_rows if r["importers"] == 0 and r["name"] in UNWIRED_EXEMPT]

        reg_rows = {}
        for g in go_names:
            if GO_PRIMARY.get(g) != pyname:
                continue
            for row in rows_by_pkg.get(g, []):
                reg_rows[row["id"]] = row
        reg_status = {"ported": 0, "partial": 0, "missing": 0, "ungated": 0, "builder": 0}
        for row in reg_rows.values():
            s = row["status"]
            if s in ("ported", "dispatch_port", "port_ported"):
                reg_status["ported"] += 1
            elif s in ("partial", "go_const_only"):
                reg_status["partial"] += 1
            elif s == "missing":
                reg_status["missing"] += 1
            elif s == "port_ungated":
                reg_status["ungated"] += 1
            elif s == "builder_only":
                reg_status["builder"] += 1
        bad_rows = [r for r in reg_rows.values() if r["status"] in BAD_ROW]

        gap_rows = {}
        for g in go_names:
            if GO_PRIMARY.get(g) != pyname:
                continue
            for gap in gaps_by_pkg.get(g, []):
                gap_rows[gap["id"]] = gap
        open_gaps = [g for g in gap_rows.values() if g["status"] == "open"]

        dim_rows = [{"id": d, "status": dims.get(d, "missing")} for d in spec["dims"]]

        py_files = pyd["files"]
        if py_files == 0:
            verdict = "test_only"
        elif spec.get("dev_only"):
            verdict = "dev_tool"
        elif not go_names:
            verdict = "missing"
        elif open_gaps:
            verdict = "partial_gap"
        elif bad_rows:
            verdict = "partial_registry"
        elif reg_status["ungated"] > 0:
            verdict = "partial_phase"
        elif any(d["status"] != "measured_aligned" for d in dim_rows) and dim_rows:
            verdict = "partial_dim"
        elif dim_rows and all(d["status"] == "measured_aligned" for d in dim_rows):
            verdict = "aligned"
        else:
            verdict = "struct_only"

        pairs.append(
            {
                "py": pyname,
                "py_files": py_files,
                "py_loc": pyd["loc"],
                "py_test_files": pyd["test_files"],
                "go": go_rows,
                "go_totals": {"files": go_files, "loc": go_loc, "test_funcs": go_tfuncs, "parity_refs": go_parity},
                "loc_ratio": round(go_loc / pyd["loc"], 2) if pyd["loc"] else None,
                "importers_min": min(importers) if importers else None,
                "unwired": unwired,
                "unwired_exempt": unwired_exempt,
                "registry": {
                    "rows": len(reg_rows),
                    "bad_rows": len(bad_rows),
                    "bad_ids": sorted(r["id"] for r in bad_rows),
                    **reg_status,
                },
                "open_gaps": [g["id"] for g in open_gaps],
                "dims": dim_rows,
                "c12": {
                    k: c12_by_pkg.get(pyname, Counter()).get(k, 0)
                    for k in ("ported", "partial", "out_of_scope", "unported")
                },
                "verdict": verdict,
                "basis": spec["basis"],
                "note": spec["note"],
            }
        )

    # Go packages not claimed by any Python row
    go_only = []
    for name, d in sorted(gos.items()):
        if name in claimed_go:
            continue
        if name not in GO_ONLY:
            sys.exit(f"Go package internal/{name} is not mapped; add it to PAIRS or GO_ONLY")
        go_only.append({**d, "name": name, "note": GO_ONLY[name].replace("{version}", go_version)})

    missing_py = sorted(set(py["packages"]) - {p["py"] for p in PAIRS})
    if missing_py:
        sys.exit(f"Python packages not in PAIRS: {missing_py}")

    # every open gap must resolve to a real file (anchors may carry :line)
    for gap in all_gaps:
        if gap["status"] == "open":
            path = re.sub(r":\d+$", "", gap["go_anchor"] or "")
            p = REPO / path
            if not p.exists():
                sys.exit(f"open gap {gap['id']} anchor does not exist: {gap['go_anchor']}")

    counts = {k: 0 for k in VERDICT_LABEL}
    for p in pairs:
        counts[p["verdict"]] += 1

    c12_totals = {k: sum(c.get(k, 0) for c in c12_by_pkg.values()) for k in ("ported", "partial", "out_of_scope", "unported")}

    summary = {
        "python_packages": len(py["packages"]),
        "python_non_test_loc": py["totals"]["non_test_loc"],
        "python_files": py["totals"]["python_files"],
        "core_tests_files": py["totals"]["core_tests_files"],
        "go_packages": len(gos),
        "go_files": sum(d["files"] for d in gos.values()),
        "go_loc": sum(d["loc"] for d in gos.values()),
        "go_test_funcs": sum(d["test_funcs"] for d in gos.values()),
        "go_only": len(go_only),
        "open_gaps": sum(1 for g in all_gaps if g["status"] == "open"),
        "fixed_gaps": sum(1 for g in all_gaps if g["status"] == "fixed"),
        "registry_rows_attributed": sum(
            len(reg.get(s, [])) for s in ("synthetic_dispatch", "events", "phase_gates")
        ),
        "registry_rows_total": sum(
            len(reg.get(s, [])) for s in ("synthetic_dispatch", "events", "phase_gates", "test_mapping")
        ),
        "ungated_total": sum(
            1 for r in reg.get("phase_gates", []) if r.get("status") == "port_ungated"
        ),
        "unwired_packages": sorted(
            n for n, d in gos.items() if d["importers"] == 0 and n not in UNWIRED_EXEMPT
        ),
        "c12_totals": c12_totals,
        "c12_baseline": c12.get("baseline_commit"),
        "verdicts": counts,
        "dims": len(dims),
        "scope_id": scope["scope_id"],
        "integration_coverage": scope["status"],
        "integration_mcp_tools": scope["counts"]["aden_tools_mcp_tools"],
    }

    data = {
        "schema_version": 1,
        "method": "静态包扫描 + 行为登记册锚点归属 + 外观维度状态；包级判定不等于逐行等价",
        "inputs": {
            "python_package_graph": sha(py["packages"]),
            "coverage_registry": sha(
                {k: reg.get(k) for k in ("synthetic_dispatch", "events", "phase_gates", "known_gaps")}
            ),
            "dimension_statuses": sha(dims),
            "c12_module_inventory": sha(c12.get("files")),
            "integration_scope": sha(scope),
        },
        "c12": {
            "baseline": c12.get("baseline_commit"),
            "totals": c12_totals,
            "by_package": {k: {s: v.get(s, 0) for s in ("ported", "partial", "out_of_scope", "unported")} for k, v in sorted(c12_by_pkg.items())},
            "unported": c12_unported,
        },
        "summary": summary,
        "integration_scope": scope,
        "dimensions": dims,
        "pairs": pairs,
        "go_only": go_only,
        "gaps": all_gaps,
        "module_notes": MODULE_NOTES,
    }
    return data


