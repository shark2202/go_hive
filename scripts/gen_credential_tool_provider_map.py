#!/usr/bin/env python3
"""Generate the credentialed tool→provider map from the upstream registry.

``CredentialStoreAdapter.get_tool_provider_map()`` builds ``tool → credential
id`` from ``CREDENTIAL_SPECS[credential].tools`` in *merge order*: when two
specs list the same tool, the one that appears later in the merged dictionary
wins. The MCP admission gate and the live-tools diagnostic read that map, so
the Go port needs the identical mapping — replaying the merge with ``ast``
(no import, no third-party dependency) is the only way to reproduce the
dictionary insertion order.

Output: ``go_hive/go-hive/internal/credentials/tool_provider_map_gen.go``.

Usage, from the repository root:

    uv run --no-project python go_hive/scripts/gen_credential_tool_provider_map.py
    uv run --no-project python go_hive/scripts/gen_credential_tool_provider_map.py --check

``--check`` regenerates in memory and exits non-zero when the checked-in file is
stale. Standard library only.
"""

from __future__ import annotations

import argparse
import ast
import sys
from pathlib import Path

SOURCE_PACKAGE = Path("tools/src/aden_tools/credentials")
OUTPUT_FILE = Path("go_hive/go-hive/internal/credentials/tool_provider_map_gen.go")

GO_HEADER = """\
// Code generated by go_hive/scripts/gen_credential_tool_provider_map.py; DO NOT EDIT.
//
// Source: {package} (CREDENTIAL_SPECS merge order, {spec_count} specs).
// Regenerate with:
//   uv run --no-project python go_hive/scripts/gen_credential_tool_provider_map.py
//
// Parity: tools/src/aden_tools/credentials/store_adapter.py::CredentialStoreAdapter.get_tool_provider_map

package credentials

// GeneratedToolProviderMap maps every credentialed tool name to the credential
// id that gates it, replayed from CREDENTIAL_SPECS in merge order: when two
// specs list the same tool, the later one wins, exactly as the adapter's
// reverse index (``self._tool_to_cred``) does.
var GeneratedToolProviderMap = map[string]string{{
"""

GO_FOOTER = "}\n"


def repo_root() -> Path:
    here = Path(__file__).resolve()
    for candidate in here.parents:
        if (candidate / SOURCE_PACKAGE).is_dir():
            return candidate
    raise SystemExit(f"gen_credential_tool_provider_map: cannot locate {SOURCE_PACKAGE} above {here}")


def literal(node: ast.AST | None) -> object | None:
    try:
        return ast.literal_eval(node) if node is not None else None
    except (ValueError, SyntaxError):
        return None


def module_constants(package: Path) -> dict[str, Path]:
    """Map every ``from .<mod> import <CONST>`` constant to its module file."""
    found: dict[str, Path] = {}
    init = package / "__init__.py"
    tree = ast.parse(init.read_text(encoding="utf-8"))
    for node in ast.walk(tree):
        if isinstance(node, ast.ImportFrom) and node.level == 1 and node.module:
            path = package / f"{node.module}.py"
            if not path.is_file():
                continue
            for alias in node.names:
                found[alias.name] = path
    return found


def dict_constants(tree: ast.Module) -> dict[str, ast.Dict]:
    out: dict[str, ast.Dict] = {}
    for node in tree.body:
        if isinstance(node, ast.Assign) and len(node.targets) == 1:
            target = node.targets[0]
            if isinstance(target, ast.Name) and isinstance(node.value, ast.Dict):
                out[target.id] = node.value
    return out


def credential_specs(tree: ast.Module) -> list[str]:
    """The ``**NAME`` sequence of ``CREDENTIAL_SPECS = {**A, **B, ...}``."""
    for node in tree.body:
        if not (isinstance(node, ast.Assign) and len(node.targets) == 1):
            continue
        target = node.targets[0]
        if not (isinstance(target, ast.Name) and target.id == "CREDENTIAL_SPECS"):
            continue
        if not isinstance(node.value, ast.Dict):
            raise SystemExit("CREDENTIAL_SPECS is not a dict literal; generator needs updating")
        order: list[str] = []
        for key, value in zip(node.value.keys, node.value.values):
            if key is None and isinstance(value, ast.Name):
                order.append(value.id)
            else:
                raise SystemExit("CREDENTIAL_SPECS uses a non-``**module`` entry; generator needs updating")
        return order
    raise SystemExit("CREDENTIAL_SPECS assignment not found in __init__.py")


def spec_tools(spec: ast.AST, list_constants: dict[str, list[str]]) -> list[str]:
    if not isinstance(spec, ast.Call):
        return []
    for keyword in spec.keywords:
        if keyword.arg != "tools":
            continue
        value = keyword.value
        if isinstance(value, ast.Name):
            return list_constants.get(value.id, [])
        resolved = literal(value)
        if isinstance(resolved, (list, tuple)):
            return [str(item) for item in resolved]
    return []


def module_lists(tree: ast.Module) -> dict[str, list[str]]:
    """Every top-level ``NAME = [..]`` list of strings (tool-name constants)."""
    out: dict[str, list[str]] = {}
    for node in tree.body:
        if not (isinstance(node, ast.Assign) and len(node.targets) == 1):
            continue
        target = node.targets[0]
        if not isinstance(target, ast.Name):
            continue
        resolved = literal(node.value)
        if isinstance(resolved, (list, tuple)):
            out[target.id] = [str(item) for item in resolved]
    return out


def build_map(package: Path) -> tuple[dict[str, str], int]:
    init_tree = ast.parse((package / "__init__.py").read_text(encoding="utf-8"))
    constants = module_constants(package)
    merge_order = credential_specs(init_tree)

    merged: dict[str, list[str]] = {}
    for constant in merge_order:
        path = constants.get(constant)
        if path is None:
            raise SystemExit(f"{constant} has no `from .<module> import` line to resolve")
        tree = ast.parse(path.read_text(encoding="utf-8"))
        dicts = dict_constants(tree)
        table = dicts.get(constant)
        if table is None:
            raise SystemExit(f"{constant} is not a top-level dict literal in {path.name}")
        list_constants = module_lists(tree)
        for key, value in zip(table.keys, table.values):
            name = literal(key)
            if not isinstance(name, str):
                raise SystemExit(f"{path.name}: {constant} has a non-literal key")
            tools = spec_tools(value, list_constants)
            # Python's ``{**a, **b}`` merge: a repeated key keeps its first
            # position but takes the later value — and _tool_to_cred iterates
            # the merged dict, so only position + final value matter.
            merged.setdefault(name, [])
            merged[name] = tools

    tool_to_cred: dict[str, str] = {}
    for name, tools in merged.items():
        for tool in tools:
            if tool:
                tool_to_cred[tool] = name
    return tool_to_cred, len(merged)


def render(tool_to_cred: dict[str, str], spec_count: int) -> str:
    lines = [GO_HEADER.format(package=SOURCE_PACKAGE, spec_count=spec_count)]
    for tool in sorted(tool_to_cred):
        provider = tool_to_cred[tool]
        lines.append(f'\t"{tool}": "{provider}",\n')
    lines.append(GO_FOOTER)
    return "".join(lines)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Generate the credentialed tool→provider map from the upstream registry")
    parser.add_argument("--check", action="store_true", help="verify the checked-in file; never writes")
    args = parser.parse_args(argv)

    root = repo_root()
    tool_to_cred, spec_count = build_map(root / SOURCE_PACKAGE)
    content = render(tool_to_cred, spec_count)
    output = root / OUTPUT_FILE

    if args.check:
        current = output.read_text(encoding="utf-8") if output.is_file() else ""
        if current != content:
            print(f"gen_credential_tool_provider_map: STALE — {OUTPUT_FILE} does not match the registry")
            return 1
        print(f"gen_credential_tool_provider_map: OK — {len(tool_to_cred)} tools across {spec_count} specs")
        return 0

    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(content, encoding="utf-8")
    print(f"gen_credential_tool_provider_map: wrote {OUTPUT_FILE} ({len(tool_to_cred)} tools, {spec_count} specs)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
